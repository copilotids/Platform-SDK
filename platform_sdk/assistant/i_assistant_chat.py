from dataclasses import dataclass
from typing import Any, Optional


@dataclass(frozen=True, kw_only=True)
class ChosenLLM:
    """The LLM chosen to handle a specific request."""

    llm_name: str
    """The name of the language model."""
    effort: Optional[str] = None
    """The effort level for the language model, if applicable."""


@dataclass(frozen=True, kw_only=True)
class BaseChatMessage:
    """Base class for messages exchanged in chat."""

    content: str
    """The content of the message."""
    metadata: Optional[dict[str, Any]] = None
    """Optional metadata associated with the message."""
    document_ids: Optional[list[int]] = None
    """Optional list of document IDs associated with the message."""


@dataclass(frozen=True, kw_only=True)
class UserMessage(BaseChatMessage):
    """A message generated by the user."""

    models_to_use: Optional[dict[str, ChosenLLM]] = None
    """
    Optional dictionary mapping roles to the chosen LLMs for handling the request.
    If None, default LLM for each role will be used.
    """


@dataclass(frozen=True, kw_only=True)
class AssistantMessage(BaseChatMessage):
    """A message generated by the assistant."""

    used_models: Optional[dict[str, ChosenLLM]] = None
    """
    Optional dictionary mapping roles to the LLMs that were actually used to handle
    the message.
    If None, default LLM for each role was used.
    """


@dataclass(frozen=True, kw_only=True)
class AssistantChat:
    """
    Protocol defining the minimal interface for a chat between a user and an assistant.
    """

    messages: list[BaseChatMessage]
    """Messages exchanged in the chat."""
    metadata: Optional[dict[str, Any]] = None
    """Optional metadata associated with the chat."""
