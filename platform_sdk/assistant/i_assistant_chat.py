from dataclasses import dataclass
from typing import Any, Literal, Optional


@dataclass(frozen=True, kw_only=True)
class LLMConfig:
    """Configuration for the language model used in the assistant chat."""

    llm_name: str
    """The name of the language model."""
    effort: Optional[str] = None
    """The effort level for the language model, if applicable."""


@dataclass(frozen=True, kw_only=True)
class AssistantChatMessage:
    """
    Protocol defining the minimal interface for a message submitted to or generated
    by an AI assistant.
    """

    user_generated: bool
    """Whether the message was generated by the user or by the AI assistant."""
    content: str
    """The content of the message."""
    metadata: Optional[dict[str, Any]] = None
    """Optional metadata associated with the message."""
    document_ids: Optional[list[str]] = None
    """Optional list of document IDs associated with the message."""
    llm_config: Optional[dict[Literal["coordinator", "subagent"], LLMConfig]] = None
    """
    Optional configuration for the language model used in the message.
    If None, the default configuration will be used.
    """


@dataclass(frozen=True, kw_only=True)
class AssistantChat:
    """
    Protocol defining the minimal interface for a chat exchanged between
    a user or system and an AI assistant.
    """

    messages: list[AssistantChatMessage]
    """Messages exchanged in the chat."""
    metadata: Optional[dict[str, Any]] = None
    """Optional metadata associated with the chat."""
